using RoyalStore.Domain.Catalog;
using RoyalStore.Domain.Fiscal;

namespace RoyalStore.Application.Sales.DTOs;

public record PosProductDto(
    Guid ProductId,
    Guid VariantId,
    string ProductName,
    string Category,
    string? CategoryColor,
    string? VariantColor,
    decimal Price,
    string? CoverImage,
    string? VariantSize,
    bool IsStockTracked,
    decimal StockQuantity,
    bool SoldOut,
    int Origin,
    int Type,
    bool IsSelectiveTax,
    string? IvaCst,
    string? IcmsCst,
    string? PisCofinsCst,
    string? DefaultCfop,
    decimal? PromotionalPrice,
    decimal? NationalRate,
    decimal? FederalRate,
    decimal? ImportedFederalRate,
    decimal? StateRate,
    decimal? MunicipalRate,
    DateOnly? EffectiveStart,
    DateOnly? EffectiveEnd,
    string? Source,
    string? Key)
{
    public static PosProductDto From(Product product, ProductVariant variant, IbptTax? ibptTax) =>
        new(
            product.Id,
            variant.Id,
            product.Name,
            product.Category.Name,
            product.Category.Color,
            variant.Color,
            variant.Price,
            product.Photos.FirstOrDefault(p => p.IsCover)?.Url,
            variant.Size,
            variant.IsStockTracked,
            variant.StockQuantity,
            variant.IsStockTracked && variant.StockQuantity == 0m,
            (int)product.Origin,
            (int)product.Type,
            product.IsSelectiveTax,
            product.IvaCst,
            product.IcmsCst,
            product.PisCofinsCst,
            product.DefaultCfop,
            variant.PromotionalPrice,
            ibptTax?.NationalRate,
            ibptTax?.FederalRate,
            ibptTax?.ImportedFederalRate,
            ibptTax?.StateRate,
            ibptTax?.MunicipalRate,
            ibptTax?.EffectiveStart,
            ibptTax?.EffectiveEnd,
            ibptTax?.Source,
            ibptTax?.Key);
}

using RoyalStore.Domain.Catalog;
using RoyalStore.Domain.Fiscal;

namespace RoyalStore.Application.Sales.DTOs;

public record PosProductDto(
    Guid ProductId,
    Guid VariantId,
    string ProductName,
    string Category,
    string? CategoryColor,
    string? VariantColor,
    decimal Price,
    string? CoverImage,
    string? VariantSize,
    bool IsStockTracked,
    decimal StockQuantity,
    bool SoldOut,
    string Origin,
    int Type,
    bool IsSelectiveTax,
    string? IvaCst,
    string? IcmsCst,
    string? PisCofinsCst,
    string? DefaultCfop,
    decimal? NationalRate,
    decimal? FederalRate,
    decimal? ImportedFederalRate,
    decimal? StateRate,
    decimal? MunicipalRate,
    DateOnly? EffectiveStart,
    DateOnly? EffectiveEnd,
    string? Source,
    string? Key)
{
    public static PosProductDto From(Product product, ProductVariant variant, IbptTax? ibptTax) =>
        new(
            product.Id,
            variant.Id,
            product.Name,
            product.Category.Name,
            product.Category.Color,
            variant.Color,
            variant.Price ?? product.BasePrice,
            product.Photos.FirstOrDefault(p => p.IsCover)?.Url,
            variant.Size,
            product.StockTrack,
            variant.StockQuantity ?? 0m,
            product.StockTrack && (variant.StockQuantity ?? 0m) == 0m,
            product.Origin,
            (int)product.Type,
            product.IsSelectiveTax ?? false,
            product.IvaCst,
            product.IcmsCst,
            product.PisCofinsCst,
            product.DefaultCfop,
            ibptTax?.NationalRate,
            ibptTax?.FederalRate,
            ibptTax?.ImportedFederalRate,
            ibptTax?.StateRate,
            ibptTax?.MunicipalRate,
            ibptTax?.EffectiveStart,
            ibptTax?.EffectiveEnd,
            ibptTax?.Source,
            ibptTax?.Key);
}
